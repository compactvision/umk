export type Professor = {
    id: number;
    first_name: string;
    last_name: string;
    email?: string;
    phone?: string | null;
    photo_url?: string | null;
    speciality?: string | null;
    biography?: string | null;
    is_active: boolean;
    offerings_count?: number;
};
export type Department = { id: number; name: string };
export type TeachingCourse = {
    id: number;
    title: string;
    code: string | null;
    semester: number | null;
    level?: { id: number; title: string; faculty: { id: number; name: string }; department_options?: Department[] };
};
export type Year = { id: number; title: string; start_date?: string; end_date?: string };
export type Assignment = {
    id: number;
    course_id: number;
    curriculum_item_id?: number | null;
    archived_at?: string | null;
    starts_on?: string | null;
    ends_on?: string | null;
    academic_semester?: { id: number; number: number; start_date: string; end_date: string } | null;
    academic_year_id: number;
    professor_id: number | null;
    is_published: boolean;
    is_optional: boolean;
    class_id: number | null;
    academic_department_id?: number | null;
    department?: Department | null;
    assistant_professor_id?: number | null;
    assistant?: Professor | null;
    group_leader_name?: string | null;
    delivery_mode?: string;
    professor?: Professor | null;
    academic_year: Year;
    course?: TeachingCourse;
    level?: { id: number; title: string; faculty: { name: string } };
    group?: { intake?: { name: string } } | null;
};
export const professorName = (professor: Professor) => `${professor.first_name} ${professor.last_name}`;
